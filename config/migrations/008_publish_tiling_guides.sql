<h2>Common causes of hollow and popped tiles</h2>
<ul>
  <li><strong>Poor adhesive coverage:</strong> when tiles are laid with "spot" adhesive instead of full coverage, air pockets are left underneath and the tile can debond over time.</li>
  <li><strong>Weak or uneven base:</strong> a screed that is crumbly, uneven or not properly bonded to the slab cannot hold the tiles firmly.</li>
  <li><strong>Temperature and humidity changes:</strong> tiles and the slab expand and contract at different rates. Without proper movement allowance, pressure builds up and tiles can lift.</li>
  <li><strong>Age of the floor:</strong> older floors simply wear out, and the bond weakens after many years.</li>
</ul>

<h2>Warning signs to watch for</h2>
<ul>
  <li>A hollow or drum-like sound when you tap the tile</li>
  <li>Hairline cracks running across one or more tiles</li>
  <li>Tiles that rock slightly underfoot, or grout lines that crumble</li>
  <li>Tiles that rise up in a ridge, often in the middle of a room</li>
</ul>

<div class="blog-callout warning">
  <h4>⚠️ Don''t wait too long</h4>
  <p>A small area of hollow tiles is usually easier to fix than a floor where many tiles have already cracked or lifted. If you notice the signs above, have the floor checked early.</p>
</div>

